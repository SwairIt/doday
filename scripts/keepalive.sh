#!/bin/sh
# Watchdog: держит сайт Doday всегда живым.
#
# Проблема, которую решает: если uvicorn запустить из интерактивной сессии
# (SSH/терминал), процесс становится её ребёнком и на ЛОГАУТЕ умирает по SIGHUP —
# сайт «переставал работать». Плюс при обычном падении/зависании его никто не
# поднимал.
#
# Этот скрипт запускается раз в минуту из FastPanel Scheduler (cron). Cron НЕ
# привязан к твоей сессии, поэтому логаут ему не страшен. Логика простая:
#   1. дёрнуть лёгкий liveness /health на :8011;
#   2. отвечает 200 — всё хорошо, выходим;
#   3. не отвечает (упал/завис) — снять процесс с порта и поднять заново,
#      ОТВЯЗАННО от сессии (setsid + nohup), чтобы новый инстанс пережил логаут.
# После падения или перезагрузки сервера сайт сам оживает в течение минуты.
#
# Установка — одна строка в FastPanel → getdoday.ru → Планировщик, под
# пользователем getdoday, расписание «каждую минуту»:
#
#   * * * * * sh /var/www/getdoday/data/www/getdoday.ru/app/scripts/keepalive.sh >> /var/www/getdoday/data/keepalive.log 2>&1
#
# /health не трогает БД, поэтому сторож перезапускает сайт ТОЛЬКО когда мёртв
# сам процесс, а не когда, например, приляжет Postgres.

PORT=8011
APP_DIR="/var/www/getdoday/data/www/getdoday.ru/app"
START="/var/www/getdoday/data/start_uvicorn.py"
UVICORN_LOG="/var/www/getdoday/data/uvicorn.log"
URL="http://127.0.0.1:${PORT}/health"

# Уже жив и отвечает — ничего не делаем (самый частый путь, быстрый выход).
if curl -fsS -m 5 "$URL" >/dev/null 2>&1; then
    exit 0
fi

echo "$(date '+%Y-%m-%d %H:%M:%S') сайт не ответил на ${URL} — поднимаю заново"

# Снимаем всё, что держит порт: упавший недопроцесс или зависший инстанс,
# который занял бы порт и не дал новому подняться.
for pid in $(lsof -ti:"${PORT}" 2>/dev/null); do
    kill -9 "$pid" 2>/dev/null || true
done
sleep 1

# Запуск ОТВЯЗАННО от текущей сессии и от самого cron:
#   setsid — новый сеанс/группа процессов (не убьётся вместе с родителем),
#   nohup  — игнорировать SIGHUP,
#   &      — в фон, чтобы скрипт сразу завершился и cron не висел.
cd "$APP_DIR" || exit 1
setsid nohup python3 "$START" >> "$UVICORN_LOG" 2>&1 &

exit 0
