"""Проверки текста до отправки модели и после ответа.

Две разные задачи:

1. `find_personal_data` — подсказка пользователю, что он собирается отправить
   провайдеру свои настоящие данные. Не блокировка: надёжно вычистить
   персональные данные регулярками невозможно, поэтому решает человек.

2. `is_unsafe_for_children` — ответы на темы, запрещённые к распространению
   среди детей (ст. 5 ч. 2 436-ФЗ). Провайдеры фильтруют сами, но
   ответственность за то, что увидит школьник, лежит на нас.
"""

from __future__ import annotations

import re

# ── персональные данные ───────────────────────────────────────────────────

_PHONE_RE = re.compile(r"(?:\+7|8)[\s\-(]*\d{3}[\s\-)]*\d{3}[\s\-]*\d{2}[\s\-]*\d{2}")
_EMAIL_RE = re.compile(r"[A-Za-z0-9._%+\-]+@[A-Za-z0-9.\-]+\.[A-Za-z]{2,}")
# «меня зовут Иван», «я Иван Петров» — самые частые способы представиться.
_SELF_INTRO_RE = re.compile(
    r"(?:меня\s+зовут|я\s+—?\s*)\s*[А-ЯЁ][а-яё]+(?:\s+[А-ЯЁ][а-яё]+)?", re.IGNORECASE
)
_SCHOOL_RE = re.compile(r"(?:школ\w*\s*№?\s*\d+|гимназ\w*\s*№?\s*\d+|лице\w*\s*№?\s*\d+)", re.I)
_ADDRESS_RE = re.compile(r"(?:ул\.|улиц\w+|проспект|переул\w+)\s+[А-ЯЁ][а-яё]+", re.IGNORECASE)


def find_personal_data(text: str) -> list[str]:
    """Что в тексте похоже на личные данные. Пустой список — ничего не нашли."""
    found: list[str] = []
    if _PHONE_RE.search(text):
        found.append("телефон")
    if _EMAIL_RE.search(text):
        found.append("почту")
    if _SELF_INTRO_RE.search(text):
        found.append("имя")
    if _SCHOOL_RE.search(text):
        found.append("номер школы")
    if _ADDRESS_RE.search(text):
        found.append("адрес")
    return found


# ── запрещённое для детей ─────────────────────────────────────────────────

# Формулировки подобраны по ст. 5 ч. 2 436-ФЗ. Проверяем ответ модели, а не
# вопрос: спросить школьник может о чём угодно, включая учебные темы вроде
# «Анна Каренина бросилась под поезд» — важно, что именно ему покажут.
_UNSAFE_PATTERNS: tuple[tuple[str, re.Pattern[str]], ...] = (
    (
        "суицид",
        re.compile(
            r"(?:как\s+(?:покончить|убить\s+себя|свести\s+счёты)"
            r"|способ\w*\s+самоубийс\w+|инструкц\w+\s+по\s+суицид\w*"
            r"|как\s+(?:правильно\s+)?(?:порезать|резать)\s+вены)",
            re.IGNORECASE,
        ),
    ),
    (
        "наркотики",
        re.compile(
            r"(?:как\s+(?:сварить|синтезиров\w+|приготовить)\s+"
            r"(?:наркот\w+|мет\w*|амфетамин\w*|героин\w*)"
            r"|где\s+купить\s+(?:наркот\w+|закладк\w+))",
            re.IGNORECASE,
        ),
    ),
    (
        "оружие и взрывчатка",
        re.compile(
            r"(?:как\s+(?:сделать|изготовить|собрать)\s+"
            r"(?:бомб\w+|взрывчат\w+|самопал\w*|оруж\w+))",
            re.IGNORECASE,
        ),
    ),
)


def is_unsafe_for_children(text: str) -> str | None:
    """Причина, по которой ответ нельзя показывать, либо None.

    Проверяем формулировки-инструкции, а не отдельные слова: упоминание
    самоубийства в разборе «Анны Карениной» — нормальная школьная тема,
    а пошаговая инструкция — нет.
    """
    for reason, pattern in _UNSAFE_PATTERNS:
        if pattern.search(text):
            return reason
    return None
